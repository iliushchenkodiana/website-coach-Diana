function applyLang(lang){
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(content[lang][key] !== undefined) el.innerHTML = content[lang][key];
  });
  document.documentElement.lang = lang === 'ua' ? 'uk' : 'en';
  const toggle = document.getElementById('langToggle');
  toggle.dataset.lang = lang;
  toggle.textContent = lang === 'ua' ? 'EN' : 'UA';
  window.__lang = lang;
  buildMarquee(lang);
  renderMonthCountdown();
}
document.getElementById('langToggle').addEventListener('click', function(){
  applyLang(this.dataset.lang === 'ua' ? 'en' : 'ua');
});

function buildMarquee(lang){
  const word = lang === 'ua' ? 'ОБЕРИ СЕБЕ' : 'CHOOSE YOURSELF';
  const dot = '<svg viewBox="0 0 20 20"><path d="M10 0L12 8L20 10L12 12L10 20L8 12L0 10L8 8Z" fill="currentColor"/></svg>';
  let html = '';
  for(let i=0;i<12;i++){ html += `<span>${word}</span>${dot}`; }
  document.getElementById('marqueeTrack').innerHTML = html;
}

